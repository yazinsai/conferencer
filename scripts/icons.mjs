#!/usr/bin/env node
/**
 * Generates `src/components/ui/icons.generated.ts` from the Solar icon set.
 *
 *   npm run icons
 *
 * Solar ships 7,627 icons across six style families — six megabytes we have no
 * business shipping to a browser. This pulls out only the icons the product
 * actually renders (a few kilobytes of path data), so `@iconify-json/solar` stays
 * a devDependency that nothing at build time or runtime imports.
 *
 * Two style families, and only two, mirroring the type system's display/body
 * split (see design.md § Iconography):
 *
 *   linear — the single voice. A hairline stroke that matches our 1px rules.
 *   bold   — one register, for filled status markers that must read at 14px.
 *
 * Adding an icon means adding it to MANIFEST below and re-running. The script
 * fails on an unknown name rather than emitting a hole.
 */

import { writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { fileURLToPath } from "node:url";

const require = createRequire(import.meta.url);
const OUT = fileURLToPath(new URL("../src/components/ui/icons.generated.ts", import.meta.url));

/** name-in-code → name-in-Solar. The left column is what components ask for. */
const MANIFEST = {
  /* chrome ------------------------------------------------------------- */
  search: "magnifier-linear",
  chevronDown: "alt-arrow-down-linear",
  chevronUp: "alt-arrow-up-linear",
  chevronRight: "alt-arrow-right-linear",
  arrowRight: "arrow-right-linear",
  close: "close-circle-linear",
  check: "check-circle-linear",
  plus: "add-circle-linear",
  lock: "lock-linear",

  /* status — the one place the bold register is allowed ----------------- */
  success: "check-circle-bold",
  warning: "danger-triangle-bold",
  info: "info-circle-bold",
  error: "close-circle-bold",
  loading: "refresh-linear",

  /* organizer navigation ------------------------------------------------ */
  dashboard: "widget-linear",
  submissions: "document-text-linear",
  abstracts: "notes-linear",
  sessions: "presentation-graph-linear",
  files: "folder-linear",
  forms: "clipboard-list-linear",
  evaluation: "checklist-minimalistic-linear",
  agenda: "calendar-linear",
  embeds: "code-square-linear",
  portals: "login-3-linear",
  tasks: "checklist-linear",
  deliverables: "inbox-linear",
  speakers: "users-group-rounded-linear",
  team: "users-group-two-rounded-linear",
  crm: "notebook-linear",
  emails: "letter-linear",
  templates: "documents-linear",
  reports: "chart-2-linear",
  settings: "settings-linear",

  /* content ------------------------------------------------------------- */
  clock: "clock-circle-linear",
  place: "map-point-linear",
  person: "user-rounded-linear",
  decision: "clipboard-check-linear",
  star: "star-linear",
  starFilled: "star-bold",
  edit: "pen-2-linear",

  /* landing page — the public site, and the three ownership guarantees --- */
  globe: "global-linear",
  unlocked: "lock-keyhole-unlocked-linear",
  database: "database-linear",
  copy: "copy-linear",
};

const solar = require("@iconify-json/solar/icons.json");

const missing = Object.values(MANIFEST).filter((name) => !solar.icons[name]);
if (missing.length) {
  console.error(`\x1b[31mUnknown Solar icons: ${missing.join(", ")}\x1b[0m`);
  process.exit(1);
}

const entries = Object.entries(MANIFEST)
  .map(([key, name]) => `  ${key}: ${JSON.stringify(solar.icons[name].body)},`)
  .join("\n");

const bytes = Object.values(MANIFEST).reduce((n, name) => n + solar.icons[name].body.length, 0);

writeFileSync(
  OUT,
  `// Generated by scripts/icons.mjs — do not edit by hand. Run \`npm run icons\`.
//
// Solar (https://icon-sets.iconify.design/solar/), MIT licensed, by 480 Design.
// Only the icons this product renders are extracted; the full set is a
// devDependency that never reaches the bundle. Two style families are in use:
// \`linear\` as the single voice, \`bold\` for filled status markers only.
//
// ${Object.keys(MANIFEST).length} icons · ${(bytes / 1024).toFixed(1)} KB of path data.

export const ICONS = {
${entries}
} as const;

export type IconName = keyof typeof ICONS;
`,
);

console.log(
  `\x1b[32m✓\x1b[0m ${Object.keys(MANIFEST).length} icons · ${(bytes / 1024).toFixed(1)} KB → src/components/ui/icons.generated.ts`,
);
